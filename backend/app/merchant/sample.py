"""Sample merchant data: reproducible, and clearly labelled as sample everywhere it is shown.

Layer 1 (payments): data/merchant_sample/transactions.csv, made by ml/make_merchant_sample.py from the TEST period of the
synthetic data (never seen by the fraud models) and already scored by the shipped XGBoost model. If the file is absent, a
built-in generator with the same columns is used so the app and tests run on a fresh clone.

Layer 2 (orders, refunds, settlements): generated from the payments with a fixed seed, with known problems planted (missing
orders, amount mismatches, duplicate references, double payments, over-refunds, short settlements...). The planted problems
are recorded in `MerchantDataset.injected` so tests can check that the reconciler finds them.
"""

from __future__ import annotations

import itertools
from pathlib import Path

import numpy as np
import pandas as pd

from .model import MerchantDataset, empty_orders, empty_refunds, empty_settlements, finalize_transactions

BACKEND = Path(__file__).resolve().parents[2]
MERCHANT_SAMPLE = BACKEND / "data" / "merchant_sample"
N_OUTLETS = 40
SEED = 11


def _load_public(top_outlets: int | None = N_OUTLETS) -> pd.DataFrame | None:
    """The sample payments: the SYNTHETIC IEEE-layout data the four fraud models were built on (test period only, so the
    models never saw it), already scored by the shipped XGBoost model. Built by ml/make_merchant_sample.py."""
    f = MERCHANT_SAMPLE / "transactions.csv"
    if not f.exists():
        return None
    t = pd.read_csv(f, parse_dates=["timestamp"]).fillna({"reasons": ""})
    return pd.DataFrame({
        "txn_ref": t["txn_ref"].astype(str), "ts": t["timestamp"], "amount_paise": (t["amount"] * 100).round().astype("int64"),
        "status": t["status"], "outlet": t["outlet"], "payer_ref": t["payer_ref"], "order_id": None,
        "fraud_prob": t["fraud_prob"], "zone": t["zone"], "reasons": t["reasons"], "_fraud": t["is_fraud"].to_numpy(),
    })


def _builtin_base(n: int = 2200, seed: int = SEED) -> pd.DataFrame:
    """Same columns as the public data, generated. Used only when the public file is not on disk."""
    rng = np.random.default_rng(seed)
    ts = pd.Timestamp("2024-01-01") + pd.to_timedelta(np.sort(rng.uniform(0, 365 * 86400, n)), unit="s")
    amt = np.clip(rng.lognormal(6.0, 1.0, n), 10, 50000).round(2)
    new_dev, ip_mis = rng.binomial(1, 0.12, n), rng.binomial(1, 0.08, n)
    p = 1 / (1 + np.exp(-(-3.8 + 1.1 * new_dev + 0.8 * ip_mis)))
    return pd.DataFrame({
        "txn_ref": [f"TXN{i:07d}" for i in range(n)], "ts": ts, "amount_paise": (amt * 100).round().astype("int64"),
        "status": rng.choice(["success", "failed", "pending"], n, p=[0.88, 0.1, 0.02]), "outlet": [f"Outlet {i + 1:02d}" for i in rng.integers(0, N_OUTLETS, n)],
        "payer_ref": [f"USR{i:05d}" for i in rng.integers(0, 700, n)], "order_id": None,
        "sig_new_device": new_dev, "sig_ip_mismatch": ip_mis, "sig_failed_attempts": rng.poisson(0.4, n), "sig_loyalty": rng.uniform(0, 1, n).round(2),
        "sig_user_avg_value": np.clip(amt * rng.uniform(0.5, 1.6, n), 20, None).round(2), "sig_recurring": rng.binomial(1, 0.2, n),
        "txn_type": rng.choice(["P2M", "Bill Payment", "Recharge", "EMI", "Subscription"], n), "payment_app": rng.choice(["GPay", "PhonePe", "Paytm", "BHIM"], n),
        "device_type": rng.choice(["Android", "iOS", "Web"], n, p=[0.7, 0.2, 0.1]), "kyc": rng.choice(["Verified", "Pending"], n, p=[0.9, 0.1]),
        "city_tier": rng.choice(["Tier 1", "Tier 2", "Tier 3"], n), "_fraud": rng.binomial(1, p),
    })


def build_sample(base: pd.DataFrame | None = None, seed: int = SEED, source_note: str | None = None) -> MerchantDataset:
    """Layer the order book, refunds and settlements on top of `base` (see module docstring)."""
    if base is None:
        pub = _load_public()
        base = pub if pub is not None else _builtin_base()
        source_note = (
            "Payments: SYNTHETIC data in the IEEE-CIS layout, the same kind the four fraud models were built on (test period only, never seen by the models). Risk zones come from the shipped XGBoost model."
            if pub is not None else "Transactions: generated by the built-in sample generator (the public dataset file is not on this machine)."
        )
    rng = np.random.default_rng(seed)
    fraud = base.pop("_fraud") if "_fraud" in base else None
    cols = {c: base[c].to_numpy() for c in base.columns}
    n = len(base)
    rows = [{c: cols[c][i] for c in cols} for i in range(n)]
    orders: list[dict] = []
    refunds: list[dict] = []
    injected: list[dict[str, str]] = []
    extra: list[dict] = []
    new_oid, new_tx, new_rf = (itertools.count(1) for _ in range(3))
    anchor = base["ts"].max()

    def order(ts, amount, outlet) -> str:
        oid = f"ORD{next(new_oid):06d}"
        orders.append({"order_id": oid, "ts": ts - pd.Timedelta(minutes=int(rng.integers(1, 10))), "amount_paise": int(amount), "outlet": outlet})
        return oid

    def refund(txn_ref, ts, amount) -> str | None:
        t = ts + pd.Timedelta(hours=int(rng.integers(2, 72)))
        if t > anchor:
            return None
        rid = f"RF{next(new_rf):05d}"
        refunds.append({"refund_id": rid, "txn_ref": txn_ref, "ts": t, "amount_paise": int(amount)})
        return rid

    for r in rows:
        u, st = rng.random(), r["status"]
        amt, ts = int(r["amount_paise"]), r["ts"]
        if st == "success":
            if u < 0.02:  # payment with no order
                injected.append({"type": "payment_without_order", "key": r["txn_ref"]})
            elif u < 0.035:  # order amount differs from the payment
                bad = int(round(amt * rng.choice([0.9, 0.95, 1.05, 1.1])))
                r["order_id"] = order(ts, bad if bad != amt else amt + 500, r["outlet"])
                injected.append({"type": "amount_mismatch", "key": r["order_id"]})
            else:
                r["order_id"] = order(ts, amt, r["outlet"])
                if u < 0.045:  # same reference recorded twice
                    extra.append({**r, "ts": ts + pd.Timedelta(seconds=int(rng.integers(30, 300)))})
                    injected.append({"type": "duplicate_reference", "key": r["txn_ref"]})
                elif u < 0.052:  # customer paid the same order twice (new reference)
                    extra.append({**r, "txn_ref": f"DBL{next(new_tx):06d}", "ts": ts + pd.Timedelta(seconds=int(rng.integers(40, 200)))})
                    injected.append({"type": "duplicate_payment", "key": r["order_id"]})
                elif u < 0.062:  # reversed
                    r["status"] = "reversed"
                    injected.append({"type": "reversal_review", "key": r["txn_ref"]})
                    if rng.random() < 0.4 and (rid := refund(r["txn_ref"], ts, amt)):
                        injected.append({"type": "refund_review", "key": rid})  # refund on a reversed payment
                elif u < 0.110:  # refunds
                    v = rng.random()
                    if v < 0.60:
                        refund(r["txn_ref"], ts, amt)
                    elif v < 0.85:
                        refund(r["txn_ref"], ts, max(100, amt // 3))
                    elif v < 0.93 and (rid := refund(r["txn_ref"], ts, int(amt * rng.uniform(1.2, 2.0)))):  # refund larger than the payment
                        injected.append({"type": "refund_review", "key": rid})
                    elif rid := refund(r["txn_ref"], ts, amt):  # the same refund recorded twice
                        refunds.append({**refunds[-1], "refund_id": f"RF{next(new_rf):05d}", "ts": refunds[-1]["ts"] + pd.Timedelta(minutes=5)})
                        injected.append({"type": "refund_review", "key": refunds[-1]["refund_id"]})
        elif st == "failed":
            if u < 0.25:
                r["order_id"] = order(ts, amt, r["outlet"])
                if rng.random() < 0.7:  # the customer retried and paid
                    extra.append({**r, "txn_ref": f"RTY{next(new_tx):06d}", "status": "success", "ts": ts + pd.Timedelta(minutes=int(rng.integers(2, 15)))})
                else:
                    injected.append({"type": "order_without_payment", "key": r["order_id"]})
        elif st == "pending" and u < 0.7:
            r["order_id"] = order(ts, amt, r["outlet"])
            injected.append({"type": "pending_payment", "key": r["txn_ref"]})

    tx = finalize_transactions(pd.DataFrame(rows + extra))
    # refunds that point at a payment that does not exist
    for _ in range(3):
        rid = f"RF{next(new_rf):05d}"
        refunds.append({"refund_id": rid, "txn_ref": f"UNKNOWN{int(rng.integers(10**6)):06d}", "ts": anchor - pd.Timedelta(days=int(rng.integers(2, 60))), "amount_paise": int(rng.integers(20000, 300000))})
        injected.append({"type": "refund_review", "key": rid})
    rf = pd.DataFrame(refunds)
    rf["ts"] = pd.to_datetime(rf["ts"])

    # Daily settlements = confirmed payments minus refunds, with a few planted shortfalls and one excess.
    ok = tx[(tx["status"] == "success") & ~tx["is_dup_row"]]
    pay = ok.groupby(ok["ts"].dt.normalize())["amount_paise"].sum()
    ref = rf.groupby(rf["ts"].dt.normalize())["amount_paise"].sum()
    st_ = pd.DataFrame({"pay": pay, "ref": ref}).fillna(0)
    st_["amount_paise"] = (st_["pay"] - st_["ref"]).astype("int64")
    st_ = st_[st_["amount_paise"] > 0]
    days = [st_.index[i] for i in rng.choice(len(st_) - 3, size=5, replace=False)]  # not the latest days: settlement lags there in real life
    for k, d in enumerate(days):
        if k < 4:
            st_.loc[d, "amount_paise"] = int(st_.loc[d, "amount_paise"] * rng.uniform(0.94, 0.98))
            injected.append({"type": "settlement_shortfall", "key": d.date().isoformat()})
        else:
            st_.loc[d, "amount_paise"] = int(st_.loc[d, "amount_paise"] * 1.03)
            injected.append({"type": "settlement_excess", "key": d.date().isoformat()})
    settlements = st_.rename_axis("date").reset_index()[["date", "amount_paise"]]
    settlements["date"] = pd.to_datetime(settlements["date"])

    ds = MerchantDataset(
        transactions=tx, orders=pd.DataFrame(orders).astype({"amount_paise": "int64"}), refunds=rf[["refund_id", "txn_ref", "ts", "amount_paise"]].astype({"amount_paise": "int64"}),
        settlements=settlements, source="sample", label="Sample business (demo data)", injected=injected,
        notes=[
            source_note or "",
            "Orders, refunds and settlements are GENERATED from those transactions with a fixed seed, with known problems planted so the reconciliation can be tested. They are not real records.",
            "Risk zones are the fraud model's own scores. A merchant normally only gets such signals if the payment provider shares them.",
            "The data is synthetic, so nothing here says anything about real UPI fraud rates.",
        ],
    )
    if fraud is not None:
        # label per base row; generated rows (retries, duplicates) inherit the label of their source via txn order, so only keep the aligned part
        lab = pd.Series(np.asarray(fraud), index=base["txn_ref"].to_numpy())
        ds.fraud_labels = tx["txn_ref"].map(lab[~lab.index.duplicated()]).astype("float")
    return ds


if __name__ == "__main__":  # quick look: python -m app.merchant.sample
    d = build_sample()
    print(len(d.transactions), "txns", len(d.orders), "orders", len(d.refunds), "refunds", len(d.settlements), "settlement days", len(d.injected), "planted")
